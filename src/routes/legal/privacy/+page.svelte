    <section>
      <h2 class="text-[15px] font-bold text-surface-900 dark:text-surface-50 mb-2">1. Information we collect</h2>

      <h3 class="text-[13px] font-semibold text-surface-800 dark:text-surface-100 mt-4 mb-1.5">Account information</h3>
      <p>When you sign up, we collect your first name, email address, and password (stored securely, hashed, by our authentication provider — we never see or store your password in plain text).</p>

      <h3 class="text-[13px] font-semibold text-surface-800 dark:text-surface-100 mt-4 mb-1.5">Profile picture</h3>
      <p>If you choose to add a profile picture, it's uploaded to our file storage and shown next to your name wherever it appears in the app (quotes, comments, reactions, leaderboards, and so on). Uploading a profile picture is entirely optional.</p>

      <h3 class="text-[13px] font-semibold text-surface-800 dark:text-surface-100 mt-4 mb-1.5">Room content</h3>
      <p>Rooms, quotes, comments, reactions, quiz results, favorites, and any group photo you upload for a room are all stored so they can be shared with the other members of that room. This content is visible to members of the room it belongs to — it isn't shared outside that room or made public.</p>

      <h3 class="text-[13px] font-semibold text-surface-800 dark:text-surface-100 mt-4 mb-1.5">Usage information</h3>
      <p>
        We use Vercel Web Analytics to understand overall traffic to QuoteStash (for example, which pages are visited
        and how often). This is a cookieless, aggregated analytics tool — it does not use cookies, does not store
        persistent identifiers on your device, and cannot be used to track you individually across sites or
        sessions. See our <a href="/legal/cookies" class="text-brand-500 hover:text-brand-600 font-medium">Cookie Policy</a> for details.
      </p>
    </section>

    <section>
      <h2 class="text-[15px] font-bold text-surface-900 dark:text-surface-50 mb-2">2. How we use your information</h2>
      <ul class="list-disc pl-5 space-y-1.5">
        <li>To create and secure your account, and let you log in.</li>
        <li>To operate the core features of QuoteStash — rooms, quotes, comments, reactions, favorites, quizzes, and leaderboards.</li>
        <li>To show your name and, if you've added one, your profile picture, to other members of rooms you're in.</li>
        <li>To send you in-app notifications about activity relevant to you (for example, someone commenting on a quote you added).</li>
        <li>To understand overall usage of the app so we can improve it.</li>
      </ul>
      <p class="mt-2">We do not sell your personal data, and we do not use your data for advertising.</p>
