      <h2 class="text-[15px] font-bold text-surface-900 dark:text-surface-50 mb-2">4. How long we keep your data</h2>
      <p>
        We keep your account and room data for as long as your account is active. If you delete your account
        (available from Settings → Manage), we delete your profile data. Content you've added to rooms you no
        longer own may be retained by that room if other members remain, since it forms part of the shared
        history of that room.
      </p>
    </section>

